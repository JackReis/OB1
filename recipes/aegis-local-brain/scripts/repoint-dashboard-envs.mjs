#!/usr/bin/env node
import { randomBytes } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const RECIPE_DIR = path.resolve(SCRIPT_DIR, "..");
const OB1_ROOT = path.resolve(RECIPE_DIR, "../..");
const DEFAULT_LOCAL_API_URL = "http://127.0.0.1:8787";
const LOCAL_API_URL = process.env.AEGIS_LOCAL_BRAIN_URL || DEFAULT_LOCAL_API_URL;

const targets = [
  {
    label: "open-brain-dashboard-next",
    file: path.join(OB1_ROOT, "dashboards/open-brain-dashboard-next/.env.local"),
    values: {
      NEXT_PUBLIC_API_URL: LOCAL_API_URL,
      AGENT_MEMORY_API_URL: LOCAL_API_URL,
      AGENT_MEMORY_WORKSPACE_ID: "aegis-local",
      AUTH_COOKIE_SECURE: "false",
    },
  },
  {
    label: "open-brain-dashboard-pro",
    file: path.join(OB1_ROOT, "dashboards/open-brain-dashboard-pro/.env.local"),
    values: {
      NEXT_PUBLIC_API_URL: LOCAL_API_URL,
    },
  },
];

function readExisting(file) {
  try {
    return fs.readFileSync(file, "utf8");
  } catch (err) {
    if (err?.code === "ENOENT") return "";
    throw err;
  }
}

function envValue(text, key) {
  const match = text.match(new RegExp(`^${key}=(.*)$`, "m"));
  return match?.[1]?.trim() || "";
}

function upsertEnv(text, key, value) {
  const line = `${key}=${value}`;
  if (new RegExp(`^${key}=`, "m").test(text)) {
    return text.replace(new RegExp(`^${key}=.*$`, "m"), line);
  }
  const prefix = text && !text.endsWith("\n") ? `${text}\n` : text;
  return `${prefix}${line}\n`;
}

function ensureSessionSecret(text) {
  const existing = envValue(text, "SESSION_SECRET");
  if (existing.length >= 32) return text;
  return upsertEnv(text, "SESSION_SECRET", randomBytes(32).toString("hex"));
}

function writeTarget(target) {
  let text = readExisting(target.file);
  if (!text) {
    text = [
      "# Aegis local Open Brain dashboard config.",
      "# Generated by OB1/recipes/aegis-local-brain/scripts/repoint-dashboard-envs.mjs.",
      "# Enter the local access key at dashboard login; this file does not store it.",
      "",
    ].join("\n");
  }
  for (const [key, value] of Object.entries(target.values)) {
    text = upsertEnv(text, key, value);
  }
  text = ensureSessionSecret(text);
  fs.writeFileSync(target.file, text.endsWith("\n") ? text : `${text}\n`, { mode: 0o600 });
  fs.chmodSync(target.file, 0o600);
  console.log(`wrote ${target.label} .env.local for ${LOCAL_API_URL} without storing the access key`);
}

for (const target of targets) {
  writeTarget(target);
}
